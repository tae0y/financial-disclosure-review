"""The task text of the original, plain-language and fidelity calls."""

EXPLANATION_ORIGINAL_TASK = """당신은 카드회사 상품광고 페이지 원문(text)이 설명의무 기준(items)을 준용했을 때
설명 품질이 적합한지 판단합니다. items의 각 항목은 code, criterion(기준 문장), applies_condition(이
기준이 적용되는 조건, 없으면 null)으로 구성됩니다. 각 항목마다 다음 순서로 답합니다.

1. applies_condition이 null이면 condition_status는 해당없음으로 둡니다. applies_condition이 있으면
   text의 내용만으로 그 조건이 실제로 성립하는지 판단합니다.
   - 성립: 조건이 성립함을 text에서 확인할 수 있음
   - 불성립: 조건이 성립하지 않음을 text에서 확인할 수 있음
   - 불명확: text만으로는 조건 성립 여부를 알 수 없음. 성립 또는 불성립으로 추측하지 않습니다.
2. condition_status가 성립 또는 해당없음일 때만 criterion을 text 기준으로 판단해 verdict를
   정합니다(적합/부적합/판정 불가). condition_status가 불성립 또는 불명확이면 verdict는 반드시
   판정 불가, quote는 반드시 빈 문자열입니다.
3. verdict가 적합이면 quote에 그 판단을 뒷받침하는 text의 문장을 그대로 인용합니다(요약·수정 금지).
   부적합이나 판정 불가는 인용할 문장이 없으면 quote를 빈 문자열로 둡니다.
4. reason에는 조건 판단과 criterion 판단의 결론과 짧은 근거만 씁니다. 내부 추론 과정을 나열하지
   않습니다.

text에 없는 내용을 있다고 답하지 않습니다. 확실하지 않으면 판정 불가로 답합니다."""

EXPLANATION_PLAIN_TASK = """당신은 쉬운말로 다시 쓴 카드회사 상품광고 페이지(text)가 설명의무 기준(items)을
준용했을 때 설명 품질이 적합한지 판단합니다. items의 각 항목은 code와 criterion(기준 문장)으로
구성됩니다. 원문과 비교하지 말고 이 text만 보고 각 항목의 verdict(적합/부적합/판정 불가)를 정합니다.
verdict가 적합이면 quote에 그 판단을 뒷받침하는 text의 문장을 그대로 인용합니다(요약·수정 금지).
부적합이나 판정 불가는 인용할 문장이 없으면 quote를 빈 문자열로 둡니다. reason에는 결론과 짧은
근거만 씁니다. text에 없는 내용을 있다고 답하지 않습니다. 확실하지 않으면 판정 불가로 답합니다."""

FIDELITY_TASK = """원문과 쉬운말이 같은 설명의무 항목을 각각 어떻게 판단했는지 비교합니다. items의 각
항목마다 원문의 판정·인용(original)과 쉬운말의 판정·인용(plain)이 주어집니다. 다음 중 하나로
분류합니다.
- 누락: 원문에 있던 내용(적합 인용)이 쉬운말에서 빠지거나 판정이 나빠짐
- 변경: 수치·조건·가능성을 나타내는 표현이 바뀜(예: 확정 표현이 "최대"·"약" 등 가능성 표현으로
  바뀌거나 조건이 사라짐). 인용된 문장의 실질 내용이 달라진 경우만 해당합니다.
- 추가: 원문에 없던 내용을 쉬운말이 새로 만들어 채움. 원문의 판정이 부적합이나 판정 불가였더라도,
  쉬운말이 새 내용을 채웠다고 해서 원문의 결함이 해결됐다고 보지 않습니다. 이 경우에도 반드시
  추가로만 분류합니다.
- 판정 불가: 인용이 불충분하거나 비교할 근거가 부족함
- 변화없음: 의미 있는 차이가 없음(표현만 다르고 내용은 같음)
reason에는 분류 근거를 한두 문장으로 씁니다."""
